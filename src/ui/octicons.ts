export type IconName = keyof typeof OCTICON_PATHS;

export const ICON_NAMES = Object.keys(OCTICON_PATHS) as IconName[];

export interface IconOptions {
  /** Without a label the icon is decorative and hidden from assistive technology. */
  readonly label?: string | undefined;
  readonly className?: ClassValue;
}

export function icon(name: IconName, options: IconOptions = {}): SVGSVGElement {
  const { label } = options;
  return svg(
    'svg',
    {
      className: ['ghx-icon', `ghx-icon--${name}`, options.className],
      viewBox: '0 0 16 16',
      width: 16,
      height: 16,
      fill: 'currentColor',
      focusable: 'false',
      role: label ? 'img' : undefined,
      'aria-label': label || undefined,
      'aria-hidden': label ? undefined : 'true',
    },
    OCTICON_PATHS[name].map((d) => svg('path', { d })),
  );
}
